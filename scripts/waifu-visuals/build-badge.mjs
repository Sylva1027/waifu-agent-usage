import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../../", import.meta.url));
const target = new URL("../../public/waifu-achievement-badge.js", import.meta.url);
const license = await readFile(new URL("../../node_modules/three/LICENSE", import.meta.url), "utf8");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["scripts/waifu-visuals/achievement-badge.js"],
  bundle: true,
  platform: "browser",
  format: "esm",
  minify: true,
  legalComments: "inline",
  banner: { js: "// Generated by npm run visuals:build:badge." },
  footer: { js: `/*\nThree.js\n${license.trim()}\n*/` },
  write: false,
});
const contents = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  const saved = (await readFile(target, "utf8")).replaceAll("\r\n", "\n");
  if (saved !== contents) {
    console.error("Badge bundle is out of date. Run npm run visuals:build:badge.");
    process.exitCode = 1;
  }
} else {
  await writeFile(target, contents);
}
