import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { buildRefraction, refractionScale } from "../motion-glass/nordify/maps.ts";

const root = fileURLToPath(new URL("../../", import.meta.url));
// One top-edge profile stretches along its straight run at every panel width.
const frameEdge = buildRefraction(16, 8);
const jobs = [
  {
    name: "Three.js",
    license: "node_modules/three/LICENSE",
    entryPoints: {
      "waifu-achievement-badge": "scripts/waifu-visuals/achievement-badge.js",
      "waifu-achievement-notice-effect": "scripts/waifu-visuals/achievement-notice-effect.js",
    },
    split: true,
  },
  {
    name: "Motion (motion-dom and motion-utils)",
    license: "node_modules/motion-dom/LICENSE.md",
    entryPoints: { "waifu-motion-controls": "scripts/motion-glass/controls.js" },
  },
  {
    name: "Nordify css-liquid-glass",
    license: "scripts/motion-glass/nordify/LICENSE",
    entryPoints: {
      "waifu-liquid-glass": "scripts/motion-glass/glass.ts",
      "waifu-frame-glass": "scripts/motion-glass/frame-glass.ts",
    },
    define: {
      __FRAME_EDGE_PNG__: JSON.stringify(frameEdge.slice.img.top),
      __FRAME_EDGE_SCALE__: String(refractionScale(frameEdge, 96, 16)),
    },
    css: true,
  },
];

for (const job of jobs) {
  const license = await readFile(path.join(root, job.license), "utf8");
  const notice = `/*\n${job.name}\n${license.trim().replaceAll("\r\n", "\n")}\n*/`;
  const result = await build({
    absWorkingDir: root,
    entryPoints: job.entryPoints,
    define: job.define,
    outdir: "public",
    ...(job.split && { splitting: true, chunkNames: "waifu-visuals-core" }),
    bundle: true,
    platform: "browser",
    format: "esm",
    minify: true,
    legalComments: "inline",
    banner: { js: "// Generated by npm run visuals:build:runtime." },
    footer: job.css ? { js: notice, css: notice } : { js: notice },
    write: false,
  });
  for (const output of result.outputFiles) {
    if (process.argv.includes("--check")) {
      const saved = (await readFile(output.path, "utf8")).replaceAll("\r\n", "\n");
      if (saved !== output.text) {
        console.error(`${path.basename(output.path)} is out of date. Run npm run visuals:build:runtime.`);
        process.exitCode = 1;
      }
    } else {
      await writeFile(output.path, output.contents);
    }
  }
}
