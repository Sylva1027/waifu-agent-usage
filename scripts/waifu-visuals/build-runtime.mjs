import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../../", import.meta.url));
const license = await readFile(new URL("../../node_modules/three/LICENSE", import.meta.url), "utf8");
const result = await build({
  absWorkingDir: root,
  entryPoints: {
    "waifu-achievement-badge": "scripts/waifu-visuals/achievement-badge.js",
    "waifu-achievement-notice-effect": "scripts/waifu-visuals/achievement-notice-effect.js",
  },
  outdir: "public",
  chunkNames: "waifu-visuals-core",
  splitting: true,
  bundle: true,
  platform: "browser",
  format: "esm",
  minify: true,
  legalComments: "inline",
  banner: { js: "// Generated by npm run visuals:build:runtime." },
  footer: { js: `/*\nThree.js\n${license.trim()}\n*/` },
  write: false,
});
for (const output of result.outputFiles) {
  if (process.argv.includes("--check")) {
    const saved = (await readFile(output.path, "utf8")).replaceAll("\r\n", "\n");
    if (saved !== output.text) {
      console.error(`${path.basename(output.path)} is out of date. Run npm run visuals:build:runtime.`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(output.path, output.contents);
  }
}
